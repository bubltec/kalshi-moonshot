"""One way to talk to the database, whichever one it is.

Production runs on Postgres (DATABASE_URL); tests and a quick local run use a SQLite file, the way the bot started. Every module goes
through `connect()` and writes the SQL it always wrote: `?` placeholders, `INSERT OR REPLACE`, `PRAGMA table_info`, rows you can index by
name or position. For Postgres this module translates those few differences in one place, so the rest of the code does not know or care:

  placeholders      `?` becomes a bound value (client-side, so a NULL or a number never needs a type guess from the server)
  upserts           `INSERT OR IGNORE / OR REPLACE` become `ON CONFLICT` using the table's own primary key
  ids               an insert into a table with an `id` returns it as `cursor.lastrowid`
  types             INTEGER is BIGINT, REAL is DOUBLE PRECISION, AUTOINCREMENT is an identity column; numerics come back as floats
  PRAGMA            table_info is answered from the catalog; the rest are no-ops

Postgres gives each logical store a schema of its own: `moonshot` and `tape` in production (DB_SCHEMA_MAIN, DB_SCHEMA_TAPE), and a throwaway one
per path in tests, so tests never touch each other or real data.
"""

from __future__ import annotations

import hashlib
import logging
import os
import re
import sqlite3
import threading
import time
from pathlib import Path
from typing import Any

from . import steptime

log = logging.getLogger("moonshot")

Row = sqlite3.Row  # what callers annotate with; a Postgres row behaves the same way
DatabaseError = sqlite3.DatabaseError
LOCAL = threading.local()

# tables whose `id` is generated by the database: an insert returns it as cursor.lastrowid
ID_TABLES = frozenset({"decisions", "orders", "jobs", "shard_moves", "screen_log", "shadow"})


def database_url() -> str:
    return os.environ.get("DATABASE_URL", "").strip()


def use_postgres() -> bool:
    return database_url().startswith(("postgres://", "postgresql://"))


def schema_for(path: Path | str, kind: str) -> str:
    """The Postgres schema for a store: named in production, derived from the path (so private to it) otherwise."""
    named = os.environ.get(f"DB_SCHEMA_{kind.upper()}", "").strip()
    if named:
        return named
    return "k" + hashlib.sha1(str(path).encode()).hexdigest()[:12] + "_" + kind


class PgRow(tuple):
    """A result row: indexable by position or by column name, like sqlite3.Row."""

    _names: tuple[str, ...]

    def __new__(cls, values: Any, names: tuple[str, ...]) -> PgRow:
        obj = super().__new__(cls, values)
        obj._names = names
        return obj

    def __getitem__(self, key: Any) -> Any:
        if isinstance(key, str):
            try:
                return tuple.__getitem__(self, self._names.index(key))
            except ValueError:
                raise IndexError(f"No item with that key: {key!r}") from None
        return tuple.__getitem__(self, key)

    def keys(self) -> list[str]:
        return list(self._names)


def _row_factory(cursor: Any) -> Any:
    names = tuple(c.name for c in (cursor.description or ()))
    return lambda values: PgRow(values, names)


def strip_comments(sql: str) -> str:
    """Remove `-- ...` comments (outside quotes) so a script can be split on its semicolons."""
    out = []
    for line in sql.splitlines():
        quotes = 0
        for i, ch in enumerate(line):
            if ch == "'":
                quotes += 1
            elif ch == "-" and line[i:i + 2] == "--" and quotes % 2 == 0:
                line = line[:i]
                break
        out.append(line)
    return "\n".join(out)


def split_statements(script: str) -> list[str]:
    parts, cur, quoted = [], [], False
    for ch in strip_comments(script):
        if ch == "'":
            quoted = not quoted
        if ch == ";" and not quoted:
            stmt = "".join(cur).strip()
            if stmt:
                parts.append(stmt)
            cur = []
        else:
            cur.append(ch)
    tail = "".join(cur).strip()
    if tail:
        parts.append(tail)
    return parts


def to_postgres_ddl(sql: str) -> str:
    sql = re.sub(r"INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", sql, flags=re.IGNORECASE)
    sql = re.sub(r"\bREAL\b", "DOUBLE PRECISION", sql, flags=re.IGNORECASE)
    sql = re.sub(r"\bINTEGER\b", "BIGINT", sql, flags=re.IGNORECASE)
    return sql


def bind(sql: str) -> str:
    """`?` placeholders to psycopg's `%s` (and a literal `%` to `%%`), leaving anything inside quotes alone."""
    out, quoted = [], False
    for ch in sql:
        if ch == "'":
            quoted = not quoted
            out.append(ch)
        elif ch == "?" and not quoted:
            out.append("%s")
        elif ch == "%":
            out.append("%%")
        else:
            out.append(ch)
    return "".join(out)


def adapt(params: Any) -> Any:
    """Python values the way SQLite stored them: a bool is 0 or 1."""
    if params is None:
        return None
    if isinstance(params, dict):
        return params
    return tuple(int(p) if isinstance(p, bool) else p for p in params)


class PgCursor:
    """What `execute` returns: fetchone / fetchall / iteration / rowcount / lastrowid, like a sqlite3 cursor."""

    def __init__(self, cur: Any, lastrowid: int = 0, rows: list | None = None):
        self._cur = cur
        self.lastrowid = lastrowid
        self._rows = rows
        self.rowcount = -1 if cur is None else cur.rowcount
        self.description = None if cur is None else cur.description

    def fetchone(self) -> Any:
        if self._rows is not None:
            return self._rows.pop(0) if self._rows else None
        try:
            return self._cur.fetchone()
        except Exception:
            return None

    def fetchall(self) -> list:
        if self._rows is not None:
            rows, self._rows = self._rows, []
            return rows
        try:
            return self._cur.fetchall()
        except Exception:
            return []

    def fetchmany(self, n: int = 1) -> list:
        return [r for r in (self.fetchone() for _ in range(n)) if r is not None]

    def __iter__(self) -> Any:
        return iter(self.fetchall())

    def close(self) -> None:
        pass


def _locked(fn):
    """One statement at a time on a connection. The worker's maintenance thread and its main loop share one Store, and so one connection; psycopg
    refuses a second command while one is in flight ('another command is already in progress') and that took the whole process down."""
    import functools

    @functools.wraps(fn)
    def wrapper(self, *args, **kwargs):
        asked = time.perf_counter()
        with self._lock:
            got = time.perf_counter()
            try:
                return fn(self, *args, **kwargs)
            finally:
                steptime.add("database lock wait", got - asked)
                steptime.add("database", time.perf_counter() - got)
    return wrapper


class PgConn:
    """A Postgres connection that speaks the dialect the code was written in (see the module docstring)."""

    is_pg = True

    def __init__(self, dsn: str, schema: str):
        self.dsn, self.schema = dsn, schema
        self._lock = threading.RLock()
        self._dirty = False  # a write is waiting for commit()
        self._pk: dict[str, tuple[list[str], list[str]]] = {}  # table -> (columns, primary key)
        self.conn: Any = None
        self._open()

    def _open(self) -> None:
        import psycopg
        from psycopg.adapt import Loader

        class FloatNumeric(Loader):  # SUM and AVG over integers come back as numeric; the code does float arithmetic
            def load(self, data: Any) -> float:
                return float(bytes(data))

        conn = psycopg.connect(self.dsn, cursor_factory=psycopg.ClientCursor, row_factory=_row_factory, autocommit=True, connect_timeout=10)
        conn.execute(f'CREATE SCHEMA IF NOT EXISTS "{self.schema}"')
        conn.execute(f'SET search_path TO "{self.schema}", public')  # public holds extensions such as pgvector
        conn.adapters.register_loader("numeric", FloatNumeric)
        conn.autocommit = False
        self.conn = conn
        self._dirty = False
        self._pk.clear()

    # ---- table facts, for upserts ----
    def _table(self, table: str) -> tuple[list[str], list[str]]:
        if table not in self._pk:
            cols = [r[0] for r in self._raw(
                "SELECT column_name FROM information_schema.columns WHERE table_schema=%s AND table_name=%s ORDER BY ordinal_position",
                (self.schema, table)).fetchall()]
            pk = [r[0] for r in self._raw(
                "SELECT a.attname FROM pg_index i JOIN pg_attribute a ON a.attrelid=i.indrelid AND a.attnum = ANY(i.indkey) "
                "WHERE i.indrelid = %s::regclass AND i.indisprimary ORDER BY array_position(i.indkey, a.attnum)",
                (f'"{self.schema}"."{table}"',)).fetchall()] if cols else []
            self._pk[table] = (cols, pk)
        return self._pk[table]

    def _upsert(self, sql: str) -> str:
        m = re.match(r"(?is)\s*INSERT\s+OR\s+(IGNORE|REPLACE)\s+INTO\s+(\w+)\s*(\(([^)]*)\))?\s*(.*)$", sql)
        if not m:
            return sql
        how, table, _grp, cols_txt, rest = m.groups()
        head = f"INSERT INTO {table} " + (f"({cols_txt}) " if cols_txt else "")
        if how.upper() == "IGNORE":
            return f"{head}{rest} ON CONFLICT DO NOTHING"
        all_cols, pk = self._table(table)
        cols = [c.strip() for c in cols_txt.split(",")] if cols_txt else all_cols
        sets = ", ".join(f"{c}=EXCLUDED.{c}" for c in cols if c not in pk)
        action = f"DO UPDATE SET {sets}" if sets else "DO NOTHING"
        return f"{head}{rest} ON CONFLICT ({', '.join(pk)}) {action}"

    def _raw(self, sql: str, params: Any = None) -> Any:
        return self.conn.execute(sql, params)

    def _end_read(self) -> None:
        if not self._dirty:
            self.conn.rollback()  # a read leaves nothing open: no idle-in-transaction connection holding the database back

    # ---- the sqlite3-shaped interface ----
    @_locked
    def execute(self, sql: str, params: Any = ()) -> PgCursor:
        text = sql.strip().rstrip(";")
        head = text[:20].lower()
        if head.startswith("pragma"):
            return self._pragma(text)
        if head.startswith(("create", "alter", "drop")):
            text = to_postgres_ddl(text)
        elif head.startswith("insert or"):
            text = self._upsert(text)
        values = adapt(params) or None
        bound = bind(text) if values else text  # with no values psycopg leaves the text alone, so a literal % needs no escaping
        last = 0
        returning = False
        m = re.match(r"(?is)\s*INSERT\s+INTO\s+(\w+)", text)
        if m and m.group(1) in ID_TABLES and "returning" not in text.lower():
            bound += " RETURNING id"
            returning = True
        try:
            cur = self.conn.execute(bound, values)
        except Exception as exc:
            self._recover(exc)
            cur = self.conn.execute(bound, values)
        is_read = head.startswith(("select", "with", "values", "show"))
        if returning:
            row = cur.fetchone()
            last = int(row[0]) if row else 0
        if not is_read:
            self._dirty = True
        if head.startswith(("create", "alter", "drop")):
            self._pk.clear()
        out = PgCursor(cur, last)
        if is_read:
            out._rows = cur.fetchall()
            self._end_read()
        return out

    def _recover(self, exc: Exception) -> None:
        """A dropped connection (a restarted database) is reopened once, if nothing was waiting to be committed."""
        import psycopg

        if isinstance(exc, (psycopg.OperationalError, psycopg.InterfaceError)) and (self.conn.closed or self.conn.broken) and not self._dirty:
            log.warning("database connection lost (%s); reconnecting", exc)
            self._open()
            return
        if not self.conn.closed:
            self.conn.rollback()
        self._dirty = False
        raise exc

    @_locked
    def executemany(self, sql: str, seq: Any) -> PgCursor:
        text = sql.strip().rstrip(";")
        if text[:20].lower().startswith("insert or"):
            text = self._upsert(text)
        rows = [adapt(r) for r in seq]
        if not rows:
            return PgCursor(None)
        bound = bind(text)
        try:
            with self.conn.pipeline():
                cur = self.conn.cursor()
                cur.executemany(bound, rows)
        except Exception as exc:
            self._recover(exc)
            raise
        self._dirty = True
        return PgCursor(cur)

    def executescript(self, script: str) -> None:
        for stmt in split_statements(script):
            self.execute(stmt)
        self.commit()

    def _pragma(self, text: str) -> PgCursor:
        m = re.match(r"(?is)pragma\s+table_info\(\s*['\"]?(\w+)['\"]?\s*\)", text)
        if m:
            cur = self._raw(
                "SELECT ordinal_position-1 AS cid, column_name AS name, data_type AS type, (is_nullable='NO')::int AS notnull, "
                "column_default AS dflt_value, 0 AS pk FROM information_schema.columns "
                "WHERE table_schema=%s AND table_name=%s ORDER BY ordinal_position", (self.schema, m.group(1)))
            rows = cur.fetchall()
            self._end_read()
            return PgCursor(None, rows=rows)
        if re.match(r"(?is)pragma\s+(quick_check|integrity_check)", text):
            return PgCursor(None, rows=[PgRow(("ok",), ("quick_check",))])
        return PgCursor(None, rows=[])

    @_locked
    def commit(self) -> None:
        if self.conn.closed:
            return
        self.conn.commit()
        self._dirty = False

    @_locked
    def rollback(self) -> None:
        if not self.conn.closed:
            self.conn.rollback()
        self._dirty = False

    def close(self) -> None:
        # connections are cached per thread and reused; closing one Store must not break the next
        if self._dirty:
            self.commit()

    def hard_close(self) -> None:
        if not self.conn.closed:
            self.conn.close()


def connect(path: Path | str, kind: str = "main", *, shared: bool = False, timeout: float = 30.0) -> Any:
    """A connection for the store at `path`. `kind` is "main" or "tape" (their Postgres schemas); `shared` lets several threads use it."""
    if not use_postgres():
        con = sqlite3.connect(str(path), timeout=timeout, check_same_thread=not shared)
        con.row_factory = sqlite3.Row
        return con
    schema = schema_for(path, kind)
    dsn = database_url()
    if shared:
        return PgConn(dsn, schema)
    cache = getattr(LOCAL, "conns", None)
    if cache is None:
        cache = LOCAL.conns = {}
    key = (dsn, schema)
    conn = cache.get(key)
    if conn is None or conn.conn.closed:
        conn = cache[key] = PgConn(dsn, schema)
    return conn


def tape_exists(path: Path | str) -> bool:
    """Whether a tape has been recorded: a file for SQLite, a populated schema for Postgres."""
    if not use_postgres():
        return Path(path).is_file()
    import psycopg

    with psycopg.connect(database_url(), autocommit=True, connect_timeout=10) as c:
        row = c.execute("SELECT 1 FROM information_schema.tables WHERE table_schema=%s AND table_name='quotes'", (schema_for(path, "tape"),)).fetchone()
    return row is not None


def is_pg(conn: Any) -> bool:
    return isinstance(conn, PgConn)


def drop_schema(schema: str) -> None:
    """Tests: remove a throwaway schema and everything in it."""
    import psycopg

    with psycopg.connect(database_url(), autocommit=True) as c:
        c.execute(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE')


def drop_test_schemas() -> int:
    """Tests: remove every schema a test run created (they all start with `k` and a hash)."""
    import psycopg

    n = 0
    with psycopg.connect(database_url(), autocommit=True) as c:
        for (name,) in c.execute("SELECT schema_name FROM information_schema.schemata WHERE schema_name ~ '^k[0-9a-f]{12}_'").fetchall():
            c.execute(f'DROP SCHEMA "{name}" CASCADE')
            n += 1
    return n
