"""Write docs/lanes.md: one plain card per live lane saying what it trades, when it buys, how much, and its exits that are ON (2026-11-10, user: "i can't even understand what a lane does").
Reads the lanes as the bot loads them (data/strategies.toml), so the card cannot drift from the file. Run after any lane change:  python scripts/lane_cards.py
"""

from pathlib import Path

from kalshi_moonshot import config, lanes

s = config.reload()
specs = lanes.lane_specs_from(s, (Path(__file__).resolve().parent.parent / "data" / "strategies.toml").read_text(), None)


def g(l, k, d=None):
    return getattr(l, k, d)


def pr(x):
    return f"{x[0]:.2f}-{x[1]:.2f}" if x else "any"


def buys(l):
    out = [f"price {pr(l.price)}"]
    if g(l, "entry_elapsed"):
        out.append(f"minutes {l.entry_elapsed[0]:g}-{l.entry_elapsed[1]:g} of the 15")
    if g(l, "record_buy"):
        out.append("buys the state record's best states (state record, rule 8)")
    if g(l, "model_buy"):
        out.append(f"buys on the curve model (top {g(l, 'model_top')} share, features {g(l, 'model_features')})")
    if g(l, "always") and not g(l, "model_buy") and not g(l, "record_buy"):
        out.append("no model edge needed: the price band and window decide")
    for k, txt in (("hot_gate", "hot-market gate"), ("timing_gate", "timing gate"), ("perp_lead_buy", "perp-lead rule"), ("require_spot_center_agree", "spot and corrected center must agree")):
        if g(l, k):
            out.append(txt)
    if g(l, "hour_drift_q", -1) >= 0:
        out.append(f"hour-drift gate (own q{g(l, 'hour_drift_q')})")
    if g(l, "entry_checks_exit"):
        out.append("skips a buy its own spot exits would sell at once")
    if g(l, "disagree_stake_factor") is not None and g(l, "require_spot_center_agree"):
        out.append("disagreeing bets skipped" if not l.disagree_stake_factor else f"disagreeing bets at {l.disagree_stake_factor:g}x stake")
    return out


def sells(l):
    out = []
    if g(l, "curve_exit", -1) >= 0:
        out.append(f"CURVE EXIT: sell when the bid net of the fee is {l.curve_exit:g} over the curve's chance ({g(l, 'curve_exit_scales')} s rate, held {g(l, 'curve_exit_persist'):g}s, any time until 8s before the close)")
    if g(l, "shock_units", 0) > 0 or g(l, "shock_bp", 0) > 0:
        out.append(f"shock exit: {g(l, 'shock_units') or str(g(l, 'shock_bp')) + ' bp'} {'typical minutes' if g(l, 'shock_units') else ''} over {g(l, 'shock_seconds'):g}s, last {g(l, 'shock_last'):g}s")
    if g(l, "late_drop_units", 0) > 0:
        out.append(f"late-drop exit: {l.late_drop_units:g} unit")
    if g(l, "value_exit", 0) > 0:
        out.append(f"value exit (confidence model), margin {l.value_exit:g}")
    if g(l, "cross_units", -1) >= 0:
        out.append(f"strike-cross exit at {l.cross_units:g} typical minutes")
    if g(l, "wrong_side_bp", 0) > 0:
        out.append(f"wrong-side exit {l.wrong_side_bp:g} bp")
    if g(l, "strike_through_sale", 0):
        out.append(f"strike-through sale {l.strike_through_sale:g}")
    if g(l, "burst_exit"):
        out.append("burst exit")
    if g(l, "stop_loss"):
        out.append("stop loss")
    return out or ["holds to settlement (no exit on)"]


lines = ["# Live lanes", "", "Generated by `scripts/lane_cards.py` from `data/strategies.toml`; do not edit by hand. A lane lists only what is ON.", ""]
for n, l in specs.items():
    if not l.enabled:
        continue
    stake = g(l, "fixed_stake") or "percent of bankroll"
    lines += [f"## {n}", "", f"*{l.label}*", "", f"- **Trades:** {len(l.series)} series ({', '.join(x.replace('15M', '') for x in l.series[:12])}), sides {'/'.join(l.sides)}"]
    lines.append("- **Buys when:** " + "; ".join(buys(l)))
    lines.append(f"- **Size:** ${stake} a bet, at most {g(l, 'max_open')} open")
    lines.append("- **Sells by:** " + "; ".join(sells(l)))
    lines.append("")
Path(__file__).resolve().parent.parent.joinpath("docs").mkdir(exist_ok=True)
Path(__file__).resolve().parent.parent.joinpath("docs", "lanes.md").write_text("\n".join(lines))
print("\n".join(lines))
